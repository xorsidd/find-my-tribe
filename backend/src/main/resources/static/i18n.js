function getLanguage() {
    return localStorage.getItem('app_language') || 'en';
}

function setLanguage(langCode) {
    if (!translations[langCode]) return;
    localStorage.setItem('app_language', langCode);
    document.documentElement.lang = langCode;
    translatePage();
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: langCode } }));
}

function t(key, defaultText = '') {
    const lang = getLanguage();
    if (translations[lang] && translations[lang][key]) {
        return translations[lang][key];
    }
    if (translations.en && translations.en[key]) {
        return translations.en[key];
    }
    return defaultText || key;
}

function translateDepartmentName(deptName) {
    const lang = getLanguage();
    if (deptTranslations[lang] && deptTranslations[lang][deptName]) {
        return deptTranslations[lang][deptName];
    }
    return deptName;
}

function translatePage() {
    const lang = getLanguage();
    
    document.querySelectorAll('[data-i18n]').forEach(elem => {
        const key = elem.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            elem.textContent = translations[lang][key];
        } else if (translations.en[key]) {
            elem.textContent = translations.en[key];
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(elem => {
        const key = elem.getAttribute('data-i18n-placeholder');
        if (translations[lang] && translations[lang][key]) {
            elem.placeholder = translations[lang][key];
        } else if (translations.en[key]) {
            elem.placeholder = translations.en[key];
        }
    });

    document.querySelectorAll('.lang-select-dropdown').forEach(select => {
        select.value = lang;
    });
}

document.addEventListener('DOMContentLoaded', () => {
    translatePage();
});
